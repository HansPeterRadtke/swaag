"""Deployment preflight must detect source/runtime drift without touching services."""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path
import subprocess
import sys


SCRIPT = Path(__file__).resolve().parents[1] / "scripts/verify-installed-package.py"
SPEC = importlib.util.spec_from_file_location("swaag_installed_preflight", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
MODULE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(MODULE)


def test_comparison_reports_exact_missing_changed_and_extra_paths(tmp_path: Path) -> None:
    original, deployed = tmp_path / "source", tmp_path / "installed"
    (original / "nested").mkdir(parents=True)
    (deployed / "nested").mkdir(parents=True)
    (original / "__init__.py").write_text("same\n")
    (deployed / "__init__.py").write_text("same\n")
    (original / "nested/logic.py").write_text("version one\n")
    (deployed / "nested/logic.py").write_text("version zero\n")
    (original / "added.py").write_text("new module\n")
    (deployed / "removed.py").write_text("old module\n")
    (deployed / "__pycache__").mkdir()
    (deployed / "__pycache__/noise.pyc").write_bytes(b"generated bytecode")
    result = MODULE.compare_packages(original, deployed)
    assert result["passed"] is False
    assert result["different"] == ["nested/logic.py"]
    assert result["source_only"] == ["added.py"]
    assert result["installed_only"] == ["removed.py"]
    assert MODULE.compare_packages(original, original)["passed"] is True


def test_preflight_rejects_symlinked_files_without_following_them(tmp_path: Path) -> None:
    original, deployed = tmp_path / "original", tmp_path / "installed"
    original.mkdir()
    deployed.mkdir()
    (original / "__init__.py").write_text("constant\n")
    (deployed / "__init__.py").write_text("constant\n")
    outside = tmp_path / "outside-secret"
    outside.write_text("must not be read or hashed\n")
    (deployed / "extra.py").symlink_to(outside)
    result = MODULE.compare_packages(original, deployed)
    assert result["passed"] is False
    assert result["installed_symlinks"] == ["extra.py"]
    assert "extra.py" not in result["installed_only"]


def test_cli_fails_closed_and_writes_optional_report(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    source = repo / "src/swaag"
    deployed = tmp_path / "deployed"
    source.mkdir(parents=True)
    deployed.mkdir()
    (source / "__init__.py").write_text("expected\n")
    (deployed / "__init__.py").write_text("outdated\n")
    output = tmp_path / "result.json"
    args = [
        sys.executable, str(SCRIPT), "--repo", str(repo),
        "--installed", str(deployed), "--output", str(output),
    ]
    check = subprocess.run(args, text=True, capture_output=True, check=False)
    assert check.returncode == 1
    assert json.loads(check.stdout)["comparison"]["different"] == ["__init__.py"]
    assert json.loads(output.read_text())["passed"] is False
    (deployed / "__init__.py").write_text("expected\n")
    good = subprocess.run(args, text=True, capture_output=True, check=False)
    assert good.returncode == 0
    assert json.loads(good.stdout)["passed"] is True


def test_missing_root_is_failure_not_success(tmp_path: Path) -> None:
    result = MODULE.main([
        "--repo", str(tmp_path / "absent"), "--installed", str(tmp_path / "also-absent"),
    ])
    assert result == 1
