"""Lossless, size-admitted durable policy and notes for fast speech turns.

No secondary LLM selector is run before the first reply. We include *all*
applicable compact rules and notes, or decline the fast path entirely. Anything
else would silently discard the user authority that the complete controller
would have seen. Source data is never treated as a new tool authorization.
"""
from __future__ import annotations

from typing import TYPE_CHECKING
from hashlib import sha256

from swaag.prompt_instructions import (
    prompt_instructions_for_kind,
    sort_prompt_instructions_by_authority,
)
from swaag.utils import stable_json_dumps

if TYPE_CHECKING:
    from swaag.runtime import AgentRuntime
    from swaag.types import SessionState


def fast_authority_fingerprint(authority: tuple[str, str]) -> str:
    """Deterministic fingerprint of exact applicable policy and note evidence."""
    return sha256(stable_json_dumps(list(authority), indent=None).encode("utf-8")).hexdigest()


def fast_authority_context(
    runtime: "AgentRuntime", state: "SessionState"
) -> tuple[str, str] | None:
    """Return exact compact applicable policy and notes or None on overflow.

    Own each existing instruction by its original source and authority. SWAAG's
    built-in core policies are expressed by the fixed quick-interface template,
    not copied as thousands of lines of orchestration-only tool guidance.
    Session/user-authored instructions remain explicit even when applicable to
    a general, ostensibly trivial conversational question.
    """
    if state.open_questions or state.deferred_tasks or state.attachments:
        return None
    # Only these *reviewed* built-in orchestration-only policies are expressed
    # by the compact fixed quick-interface contract. A future/new core policy
    # must never vanish simply because its source label says swaag_core.
    reviewed_core = {
        # Hash the exact reviewed instructions generated by
        # CommunicationService._orchestrator_state. A policy with the same ID
        # but changed contents may have new user-facing implications: it must
        # not be dropped merely because it reuses an old source identifier.
        "instruction_swaag_orchestrator_role_v4":
            "bf6fb176a95c7cc2289808ce4abd5660c4637d9bafc3eb9d45b8f0b55c47f624",
        "instruction_swaag_user_controls_v6":
            "cce21d28d91682f6381355c41c22ac8b49d41e2f4c089e7ebc7cd97bc5fea822",
    }
    def covered_by_fast_core_template(item) -> bool:
        return (item.source_kind == "swaag_core"
                and item.authority == "project_policy"
                and item.source_ref == "infra-guidelines/agents-orchestration"
                and item.instruction_id in reviewed_core
                and sha256(item.content.encode("utf-8")).hexdigest()
                    == reviewed_core[item.instruction_id])

    session = [item for item in state.prompt_instructions
               if not covered_by_fast_core_template(item)]
    instructions = [("session", item) for item in prompt_instructions_for_kind(
        session, "orchestrator_interaction")]
    for contributor in runtime.system_prompt_contributors:
        if not contributor.enabled(runtime):
            continue
        store = getattr(contributor, "store", None)
        if store is None:
            # Never ignore an unknown mandatory extension's governing policy.
            return None
        if store.has_any_events():
            instructions.extend(("user", item) for item in prompt_instructions_for_kind(
                store.list(), "orchestrator_interaction"))
    ranked = sort_prompt_instructions_by_authority([item for _, item in instructions])
    entries = []
    for item in ranked:
        source = next(src for src, matched in instructions if matched is item)
        entries.append({
            "instruction_id": item.instruction_id,
            "title": item.title,
            "content": item.content,
            "authority": item.authority,
            "source_kind": item.source_kind,
            "source_ref": item.source_ref,
            "categories": item.categories,
            "specificity": item.specificity,
            "updated_at": item.updated_at,
            "store": source,
        })
    policy_text = stable_json_dumps(entries, indent=None) if entries else ""
    if len(policy_text) > runtime.config.communication.fast_policy_max_chars:
        return None
    notes = [
        {"note_id": note.note_id, "title": note.title,
         "content": note.content, "categories": note.categories,
         "updated_at": note.updated_at, "metadata": note.metadata}
        for note in state.notes
    ]
    notes_text = stable_json_dumps(notes, indent=None) if notes else ""
    if len(notes_text) > runtime.config.communication.fast_notes_max_chars:
        return None
    return policy_text, notes_text
