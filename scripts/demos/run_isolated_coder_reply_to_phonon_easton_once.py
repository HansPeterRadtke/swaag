#!/usr/bin/env python3
"""Synthesize ONE prior genuinely generated local Coder no-action reply via Phonon.

The response was generated by one unique previous Qwen Coder inference using
a real recorded public Whisper transcript. This tool does NOT re-run Whisper
or Coder; it takes the source-linked frozen private model result transferred
to the Jetson and sends one new TTS-only request to existing Phonon Easton
loopback 15305. It saves WAV privately: NO phone playback, SWAAG server
turn, speaker verification, tools, external provider, user Send or owner
account action. Do not reissue an uncertain/failed TTS request.
"""
from __future__ import annotations
import argparse,audioop,datetime,hashlib,io,json,os,time,urllib.request,wave
from pathlib import Path

CODER_RESULT_SHA='05b1181c76c8c3e1986a3138b34fbc4ca415b282246be4656fdc89d117b5c54b'
CODER_TEXT_SHA='35f5a465cfba2db4378b12e4f0049313a8946bbab1024e0fe532c022d1c708af'
WHISPER_REAL_TRANSCRIPT_SHA='9249355bc1af6b313f1bbff87bcb834efbcfe52ec396f847c6df6c550b5bad2a'
ALIAS='qwen3-coder-30b-a3b-instruct-q4-k-m'
PHONON_HEALTH='http://127.0.0.1:15305/health'
PHONON_SYNTH='http://127.0.0.1:15305/synthesize'
OPTIN='SWAAG_W73_ONE_ACTUAL_PHONON_TTS_OF_PRIOR_CODER_NOACTION_REPLY'


def sha(p:Path)->str:return hashlib.sha256(p.read_bytes()).hexdigest()
def check(model_result:Path)->str:
    if not model_result.is_file() or model_result.is_symlink() or sha(model_result)!=CODER_RESULT_SHA:
        raise ValueError('Prior immutable real resident Coder response not available/source-pinned')
    j=json.loads(model_result.read_text())
    text=j.get('response_text')
    if (j.get('status')!='real_resident_Coder_text_response_to_prior_actual_Whisper_noaction'
        or j.get('model')!=ALIAS or j.get('original_ASR_transcript_SHA256')!=WHISPER_REAL_TRANSCRIPT_SHA
        or j.get('actual_new_model_request_count')!=1 or j.get('actual_tool_calls')!=0
        or j.get('actual_live_SWAAG_agent_turn_or_external_action') is not False
        or not isinstance(text,str) or len(text)>160 or len(text)<15
        or hashlib.sha256(text.encode()).hexdigest()!=CODER_TEXT_SHA
        or '\n' in text or '<' in text or '>' in text):
        raise ValueError('Actual prior resident model text is not safe one-use speech payload')
    return text

def unique_json(path:Path,content):
    fd=os.open(path,os.O_CREAT|os.O_EXCL|os.O_WRONLY|os.O_NOFOLLOW,0o600)
    with os.fdopen(fd,'w') as f:json.dump(content,f,indent=2,ensure_ascii=False);f.flush();os.fsync(f.fileno())

def main(argv=None):
    a=argparse.ArgumentParser(description=__doc__)
    a.add_argument('--real-coder-result',type=Path,required=True)
    a.add_argument('--private-output',type=Path,required=True)
    a.add_argument('--run',action='store_true')
    opt=a.parse_args(argv)
    text=check(opt.real_coder_result)
    if not opt.run:
        print(json.dumps({'status':'source_pinned_real_local_Coder_text_only_tts_preflight',
          'Coder_text_SHA256':CODER_TEXT_SHA,'speech_text_characters':len(text),
          'new_TTS_requests':0,'not_an_actual_owner_voice_action':True}))
        return 0
    if os.getenv(OPTIN)!='1':raise ValueError('New one-time TTS opt-in required')
    out=opt.private_output
    if out.exists() or out.is_symlink() or not out.is_absolute() or not str(out).startswith('/data/var/swaag-benchmarks/'):
        raise FileExistsError('Prior/uncertain TTS result must never be repeated')
    with urllib.request.urlopen(PHONON_HEALTH,timeout=4) as resp:
        health=json.load(resp)
        health_status=resp.status
    if (health_status!=200 or health.get('ok') is not True
        or health.get('engine')!='phonon_31m_easton_cpu' or health.get('speaker')!='Easton'):
        raise RuntimeError('Local Phonon engine or speaker not the owner-approved known voice')
    out.mkdir(mode=0o700,parents=True,exist_ok=False);os.chmod(out,0o700)
    unique_json(out/'attempt.json',{'at_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),
       'prior_model_result_SHA256':CODER_RESULT_SHA,'actual_generated_spoken_text_SHA256':CODER_TEXT_SHA,
       'service':PHONON_SYNTH,'speaker':'Easton','request_count_max':1,
       'no_external_provider_tools_physical_phone_or_user_action':True,'do_not_replay_unknown_or_finished_request':True})
    start=time.perf_counter()
    result={'status':'failed_or_unknown','prior_Coder_result_sha256':CODER_RESULT_SHA,
      'prior_real_Whisper_transcript_sha256':WHISPER_REAL_TRANSCRIPT_SHA,
      'actual_noaction_Coder_response_sha256':CODER_TEXT_SHA,
      'real_phonon_tts_attempts':0,'real_external_tool_provider_calls':0,
      'physical_owner_phone_audio_playback':False,'real_SWAAG_agent_turn_executed':False,
      'TTS_speaker':'Easton','actual_TTS_engine':'phonon_31m_easton_cpu'}
    try:
        body={'text':text,'sample_rate':16000}
        request=urllib.request.Request(PHONON_SYNTH,data=json.dumps(body).encode(),
             headers={'Content-Type':'application/json'},method='POST')
        result['real_phonon_tts_attempts']=1
        with urllib.request.urlopen(request,timeout=42) as resp:
            status=resp.status
            ctype=resp.headers.get('Content-Type','')
            wav=resp.read(3_000_001)
            synth_header=resp.headers.get('X-TTS-Seconds')
        if status!=200 or not ctype.startswith('audio/wav') or not 10000<len(wav)<3000000:
            raise ValueError('Phonon response not a valid audio/wav signal')
        with wave.open(io.BytesIO(wav),'rb') as check_wav:
            if (check_wav.getnchannels(),check_wav.getsampwidth(),check_wav.getframerate())!=(1,2,16000):
                raise ValueError('Phonon output mismatched expected mono 16kHz PCM format')
            duration=check_wav.getnframes()/check_wav.getframerate()
            samples=check_wav.readframes(check_wav.getnframes())
            if not 0.3<duration<24 or audioop.rms(samples,2)<60:
                raise ValueError('Phonon output unintelligible/silent or duration outside test bound')
        path=out/'real_coder_reply_phonon_easton.wav'
        fd=os.open(path,os.O_CREAT|os.O_EXCL|os.O_WRONLY|os.O_NOFOLLOW,0o600)
        with os.fdopen(fd,'wb') as f:f.write(wav);f.flush();os.fsync(f.fileno())
        result.update({'status':'real_Phonon_Easton_synthesized_prior_resident_Coder_response_noaction',
            'actual_Phonon_HTTP_status':status,
            'actual_audio_file_path':str(path),'actual_audio_SHA256':hashlib.sha256(wav).hexdigest(),
            'actual_audio_byte_size':len(wav),'actual_audio_seconds':round(duration,3),
            'actual_audio_RMS':audioop.rms(samples,2),'reported_TTS_seconds':synth_header,
            'same_actual_model_text_used_to_synthesize':True})
    except BaseException as e:
        result['error_type']=type(e).__name__;result['error_detail_private']=str(e)[:200]
    finally:
        result['wall_seconds']=round(time.perf_counter()-start,3)
        unique_json(out/'result.json',result)
    print(json.dumps({k:result.get(k) for k in ('status','error_type','real_phonon_tts_attempts','wall_seconds','actual_audio_seconds','actual_audio_byte_size')},sort_keys=True))
    return 0 if result['status']=='real_Phonon_Easton_synthesized_prior_resident_Coder_response_noaction' else 3

if __name__=='__main__':raise SystemExit(main())
